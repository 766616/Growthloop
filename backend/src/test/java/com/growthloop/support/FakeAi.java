package com.growthloop.support;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.util.*;

/**
 * Deterministic stand-in for the Python AI service, used by integration tests.
 * It reads the real payload built by AnalysisService and answers in the same JSON shape
 * as the FastAPI service, so the Java persistence/mapping code is exercised end to end.
 * (The Python engines themselves are tested separately with pytest.)
 */
public final class FakeAi {
    private FakeAi() {}

    public static JsonNode respond(ObjectMapper mapper, String path, Object payload) {
        JsonNode p = mapper.valueToTree(payload);
        Map<String, Object> risk = risk();
        Map<String, Object> gap = gap(p);
        List<Map<String, Object>> matches = matches(p);
        Object out = switch (path) {
            case "/risk" -> risk;
            case "/skill-gap" -> gap;
            case "/match" -> Map.of("matches", matches);
            case "/model/retrain" -> Map.of("retrained", true);
            default -> {
                List<Map<String, Object>> roadmap = new ArrayList<>();
                int order = 1;
                for (Object o : (List<?>) gap.get("missing")) {
                    @SuppressWarnings("unchecked") Map<String, Object> m = (Map<String, Object>) o;
                    Map<String, Object> item = new LinkedHashMap<>();
                    item.put("order", order);
                    item.put("skill_id", m.get("skill_id"));
                    item.put("skill", m.get("skill"));
                    item.put("priority", order <= 2 ? "HIGH" : "MEDIUM");
                    item.put("prerequisites", List.of());
                    item.put("ready_now", order == 1);
                    item.put("status", "NOT_STARTED");
                    item.put("practice_task", "Practice " + m.get("skill"));
                    item.put("estimated_hours", 10);
                    item.put("resource_ids", List.of());
                    item.put("reason", "Required for the career goal");
                    roadmap.add(item);
                    order++;
                }
                Map<String, Object> rec = new LinkedHashMap<>();
                rec.put("type", "SKILL");
                rec.put("priority", 1);
                rec.put("title", roadmap.isEmpty() ? "Keep practising" : "Learn " + roadmap.get(0).get("skill"));
                rec.put("description", "Generated by the test AI");
                rec.put("payload", Map.of());
                Map<String, Object> r = new LinkedHashMap<>();
                r.put("risk", risk);
                r.put("skill_gap", gap);
                r.put("matches", matches);
                r.put("roadmap", roadmap);
                r.put("recommendations", List.of(rec));
                r.put("next_action", "Start with the first roadmap item");
                r.put("warnings", List.of());
                yield r;
            }
        };
        return mapper.valueToTree(out);
    }

    private static Map<String, Object> risk() {
        Map<String, Object> r = new LinkedHashMap<>();
        r.put("risk_level", "MEDIUM");
        r.put("probability", 0.42);
        r.put("indicators", List.of("Pending assignments"));
        r.put("suggested_actions", List.of("Book a mentor session"));
        r.put("features", Map.of("avg_pct", 61.0));
        r.put("model", Map.of("model_version", "test-fake"));
        return r;
    }

    private static Map<String, Object> gap(JsonNode p) {
        Set<String> have = new HashSet<>();
        p.path("student").path("skills").forEach(s -> have.add(s.path("name").asText().toLowerCase()));
        List<Map<String, Object>> existing = new ArrayList<>();
        List<Map<String, Object>> missing = new ArrayList<>();
        for (JsonNode req : p.path("student").path("career_goal").path("required_skills")) {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("skill_id", req.path("skill_id").asLong());
            m.put("skill", req.path("name").asText());
            (have.contains(req.path("name").asText().toLowerCase()) ? existing : missing).add(m);
        }
        int total = existing.size() + missing.size();
        Map<String, Object> g = new LinkedHashMap<>();
        g.put("coverage_percent", total == 0 ? 0 : Math.round(100.0 * existing.size() / total));
        g.put("existing", existing);
        g.put("partial", List.of());
        g.put("missing", missing);
        g.put("recommended_next", missing.stream().limit(3).toList());
        return g;
    }

    private static List<Map<String, Object>> matches(JsonNode p) {
        List<Map<String, Object>> out = new ArrayList<>();
        for (JsonNode c : p.path("candidates")) {
            if (!"MENTOR".equals(c.path("type").asText())) continue;
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("user_id", c.path("user_id").asLong());
            m.put("name", c.path("name").asText());
            m.put("type", "MENTOR");
            m.put("score", 0.8 - out.size() * 0.1);
            m.put("reasons", List.of("Strong in skills you need"));
            m.put("can_help_with", List.of("SQL"));
            out.add(m);
        }
        return out;
    }
}
